"""Human review records and judge–human agreement helpers."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from finance_eval.schema import HumanRubricScores

# Only these sources count as human review in metrics and status fields.
INDEPENDENT_HUMAN_SOURCES = frozenset({"human_independent", "adjudicated_human"})
SEED_SOURCE = "seeded_demo"
SEED_REVIEWER = "seed-script (not a person)"
PLACEHOLDER_DOMAINS = ("@example.com", "@example.org", "@example.net")


class ReviewProvenanceError(ValueError):
    """A review row claims human provenance it cannot have."""


def is_independent_human(row: dict[str, Any]) -> bool:
    return row.get("source") in INDEPENDENT_HUMAN_SOURCES


def validate_review_row(row: dict[str, Any]) -> None:
    reviewer = str(row.get("reviewer") or "")
    if is_independent_human(row):
        if not reviewer or reviewer.endswith(PLACEHOLDER_DOMAINS) or reviewer == SEED_REVIEWER:
            raise ReviewProvenanceError(f"{row.get('case_id')}: human review needs a real reviewer id, got {reviewer!r}")
        if row.get("seeded") is True:
            raise ReviewProvenanceError(f"{row.get('case_id')}: seeded rows cannot claim human provenance")


def load_reviews(path: Path) -> dict[str, dict[str, Any]]:
    if not path.exists():
        return {}
    out: dict[str, dict[str, Any]] = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        row = json.loads(line)
        validate_review_row(row)
        out[row["case_id"]] = row
    return out


def agreement_rate(pairs: list[tuple[str, str]]) -> float | None:
    if not pairs:
        return None
    agree = sum(1 for a, b in pairs if a == b)
    return agree / len(pairs)


def seed_demo_reviews(case_results: list[dict[str, Any]], path: Path, sample_n: int = 20) -> list[dict[str, Any]]:
    """Write DEMO review rows that exercise the review pipeline.

    These rows are generated by code from the deterministic result (plus one
    forced disagreement). They are not human judgments and are labelled
    ``source=seeded_demo`` / ``seeded=True``. Refuses to overwrite a file that
    already contains non-seed rows so real reviews are never clobbered.
    """
    if path.exists():
        existing = load_reviews(path)
        if any(r.get("source") != SEED_SOURCE for r in existing.values()):
            raise FileExistsError(f"{path} contains non-seed reviews; refusing to overwrite")
    selected = case_results[:sample_n]
    # Force one disagreement for pipeline demo: first failing case, human marks pass.
    disagree_id = next((item["case_id"] for item in selected if not item.get("passed")), None)
    rows: list[dict[str, Any]] = []
    for item in selected:
        passed = bool(item.get("passed"))
        decision = "pass" if passed else "fail"
        notes = "Seeded demo row generated by code; not a human judgment."
        if disagree_id and item.get("case_id") == disagree_id:
            decision = "pass"
            notes = "Intentional disagreement seed: human overrides deterministic fail."
        scores = HumanRubricScores(
            correctness=5 if decision == "pass" else 2,
            reasoning=4 if decision == "pass" else 2,
            completeness=4 if decision == "pass" else 2,
            domain_validity=5 if decision == "pass" else 2,
            evidence_quality=4 if decision == "pass" else 2,
            financial_risk="low" if decision == "pass" else "high",
            severity="none" if decision == "pass" else "high",
            decision=decision,  # type: ignore[arg-type]
            notes=notes,
        )
        rows.append(
            {
                "case_id": item["case_id"],
                "reviewer": SEED_REVIEWER,
                "source": SEED_SOURCE,
                "seeded": True,
                **scores.model_dump(),
                "judge_decision": item.get("judge", {}).get("decision"),
            }
        )
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(json.dumps(r) for r in rows) + "\n", encoding="utf-8")
    return rows


def seed_human_reviews(case_results: list[dict[str, Any]], path: Path, sample_n: int = 20) -> list[dict[str, Any]]:
    """Deprecated alias for :func:`seed_demo_reviews` (rows are not human)."""
    return seed_demo_reviews(case_results, path, sample_n=sample_n)
